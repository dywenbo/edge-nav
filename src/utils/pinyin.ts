const INITIALS = (() => {
  const map = new Map<string, string>()
  for (const [letter, chars] of Object.entries(GROUPS)) {
    for (const ch of chars) if (!map.has(ch)) map.set(ch, letter)
  }
  return map
})()

/**
 * 生成搜索别名：中文取首字母，ASCII 字母/数字原样保留（小写），其余字符跳过。
 * 例：「腾讯文档」→ txwd；「Vue 文档」→ vuewd
 */
export function suggestAlias(title: string): string {
  let out = ''
  for (const ch of (title || '').trim()) {
    if (/[a-z0-9]/i.test(ch)) out += ch.toLowerCase()
    else if (INITIALS.has(ch)) out += INITIALS.get(ch)
    if (out.length >= 24) break
  }
  return out
}
